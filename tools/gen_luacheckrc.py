def load(package_dir):
    api = json.load(open(os.path.join(package_dir, "files", "vscripts", "api.json"), encoding="utf-8"))
    en = json.load(open(os.path.join(package_dir, "files", "vscripts", "enums.json"), encoding="utf-8"))
    names = set(EXTRA)
    for a in api:
        if a["kind"] == "function":
            names.add(a["name"])
        elif a["kind"] == "class":
            names.add(a["name"])
            for k in ("instance", "clientName"):
                if a.get(k):
                    names.add(a[k])
    for e in en:
        names.add(e["name"])
        for m in e.get("members", []):
            names.add(m["name"])
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--package")
    ap.add_argument("--version", default="0.47.2")
    a = ap.parse_args()
    pkg = a.package
    tmp = None
    if not pkg:
        url = f"https://registry.npmjs.org/@moddota/dota-data/-/dota-data-{a.version}.tgz"
        data = urllib.request.urlopen(url, timeout=120).read()
        tmp = tempfile.mkdtemp(prefix="dota-data-")
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as t:
            t.extractall(tmp)
        pkg = os.path.join(tmp, "package")
    names = load(pkg)
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    out = [f"-- Generated by tools/gen_luacheckrc.py from @moddota/dota-data {a.version} (api.json + enums.json).",
           "-- Do not edit by hand: rerun the generator after a Dota patch and commit the result.",
           "std = 'luajit'", "max_line_length = 160", "codes = true",
           "-- Dota VScript is Lua 5.1 without `goto`; keep the checks strict where it is cheap.",
           "ignore = {", "  '212', -- unused argument (keys/self in handlers)", "  '631', -- line too long: stylua handles layout", "}",
           "exclude_files = { 'tools/vanilla/**', 'logs/**', 'game/dota_addons/attackcopy/scripts/vscripts/statcollection/**' }",
           "read_globals = {"]
    out += [f"  '{n}'," for n in sorted(names)]
    out += ["}", "-- Addon-level globals the engine requires us to define (one per file; everything else is `local`).",
            "globals = { 'Activate', 'Precache', 'GameMode', 'AOHGameMode' }",
            "-- Tests define the engine globals (the stub) and the helper table T.",
            'files["tests/dota_stub.lua"] = { globals = { "class", "IsServer", "IsClient", "IsInToolsMode", "Vector", "RandomInt",',
            '  "RandomFloat", "print", "Dynamic_Wrap", "LinkLuaModifier", "Msg", "Warning", "GameRules", "Timers" } }',
            'files["tests/run.lua"] = { globals = { "T" } }',
            'files["tests/test_*.lua"] = { read_globals = { "T" } }']
    with open(os.path.join(root, ".luacheckrc"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f".luacheckrc: {len(names)} read_globals from dota-data {a.version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
