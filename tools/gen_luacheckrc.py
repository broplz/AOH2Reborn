#!/usr/bin/env python3
"""Regenerate .luacheckrc from @moddota/dota-data (owner-run; needs network or a local tarball).

    tools/gen_luacheckrc.py [--package <dir with files/vscripts/api.json>] [--version 0.47.2]

Without --package it downloads https://registry.npmjs.org/@moddota/dota-data/-/dota-data-<v>.tgz
into a temp dir. read_globals = every global function, class, instance (GameRules, …), enum and
enum member in the dump, plus the Lua-side names the engine provides that the dump omits.
"""
import argparse
import io
import json
import os
import sys
import tarfile
import tempfile
import urllib.request

